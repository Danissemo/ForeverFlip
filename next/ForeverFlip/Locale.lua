T.current = "en"

function T.apply(language)
    if language == "en" or language == "uk" then
        T.current = language
        return
    end
    local client = GetLocale and GetLocale() or "enUS"
    T.current = client == "ukUA" and "uk" or "en"
end

function T.text(s)
    if T.current == "uk" then
        return T.uk[s] or s
    end
    if s == "saved" then
        return "Saved."
    elseif s == "reload" then
        return "Language saved. Type /reload."
    end
    return s
end
