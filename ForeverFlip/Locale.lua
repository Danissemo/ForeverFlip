function T.current()
    local ui = type(F.db) == "table" and F.db.ui
    local override = type(ui) == "table" and ui.language
    return override or (GetLocale and GetLocale()) or "enUS"
end
function T.text(source, en)
    local language = T.current()
    if language == "ukUA" or language == "uk" then
        return T.uk[en] or en or source
    end
    return ((en or source):gsub("→", "->"):gsub("←", "<-"))
end
function T.message(value)
    if T.current() == "ukUA" then
        if T.uk[value] then
            return T.uk[value]
        end
        if type(value) == "string" then
            for _, prefix in ipairs({ "search_error: ", "Invalid legacy row " }) do
                if value:sub(1, #prefix) == prefix then
                    return T.uk[prefix] .. value:sub(#prefix + 1)
                end
            end
        end
        return value
    end
    return value
end
function T.choose(value)
    local aliases = {
        uk = "ukUA",
        ua = "ukUA",
        ukUA = "ukUA",
        en = "enUS",
        enUS = "enUS",
        auto = "auto",
    }
    local language = aliases[value]
    if not language or not F.db or not F.Store.writable(F.db) then
        return false
    end
    F.db.ui.language = language ~= "auto" and language or nil
    return true
end
